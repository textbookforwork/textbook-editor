import { start, login } from './common.mjs';
const SP = process.argv[2];
const { b, p } = await start(); p.setDefaultTimeout(8000);
await p.route('**/api.microlink.io/**', r => r.abort());
await login(p);
await p.locator('button[title="切換身分、登出"]').click(); await p.waitForTimeout(300);
await p.getByRole('menuitemradio', { name: '系統管理員' }).click(); await p.waitForTimeout(600);
await p.getByRole('button', { name: '建立教材' }).first().click(); await p.waitForTimeout(500);
const dlg = p.getByRole('dialog', { name: '建立教材' });
await dlg.getByPlaceholder('請輸入教材名稱').fill('木蘭詩');
await dlg.getByPlaceholder('請輸入出版社名稱').fill('範例');
await dlg.getByRole('radio', { name: '國小' }).click(); await p.waitForTimeout(300);
await dlg.screenshot({ path: SP + '/k_sub_es.png' });
await dlg.getByRole('radio', { name: '國中' }).click(); await p.waitForTimeout(300);
await dlg.screenshot({ path: SP + '/k_sub_jh.png' });
await dlg.getByRole('button', { name: '建立', exact: true }).click(); await p.waitForTimeout(2500);
await p.locator('button[title="教材設定、匯入"]').click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: '匯入 .md 檔' }).click(); await p.waitForTimeout(600);
const imp = p.getByRole('dialog', { name: '匯入 .md 檔' });
await imp.screenshot({ path: SP + '/k_import.png' });
await imp.getByRole('button', { name: '國文（範例・直排）' }).click(); await p.waitForTimeout(400);
await imp.getByRole('button', { name: '匯入', exact: true }).click(); await p.waitForTimeout(2500);
await p.mouse.click(1430, 880); await p.waitForTimeout(300);
await p.locator('button[title^="發布到書櫃"]').click(); await p.waitForTimeout(800);
const pub = p.getByRole('dialog', { name: '教材已發布' });
await pub.screenshot({ path: SP + '/k_pub.png' });
await pub.getByRole('button', { name: '前往上傳' }).click(); await p.waitForTimeout(800);
await p.getByRole('dialog', { name: '課本封面' }).screenshot({ path: SP + '/k_cover.png' });
await b.close();
